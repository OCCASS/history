"""Разбивает ядро из 300 карточек на тематические стопки по 13–28 карточек.

Стопка — это связный сюжет: несколько подряд идущих глав учебника, внутри
карточки выстроены как рассказ (события по хронологии, затем персоны,
понятия и культура). Результат дописывается в core.js как HCORE.blocks —
приложение (index.html) рисует по нему «путь» из стопок с прогрессом.

Запуск:  python3 tools/gen-core-blocks.py [--preview]
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def load_js(path, var):
    src = open(os.path.join(ROOT, path), encoding='utf-8').read()
    return json.loads(src[src.index('=') + 1:].strip().rstrip(';'))

