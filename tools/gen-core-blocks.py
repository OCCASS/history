# ---------- карточки ядра ----------
def ch_of(key):
    kind, rest = key.split(':', 1)
    return int(rest.split(':')[0]) if kind == 't' else int(re.match(r'c(\d+)_', rest).group(1))

KIND = {'e': 'event', 'p': 'person', 'c': 'culture', 't': 'term'}
KIND_ORDER = {'event': 0, 'person': 1, 'term': 2, 'culture': 3}

CARDS = {}
for ch in D['chapters']:
    n = ch['chapter']
    for e in ch.get('events', []):
        CARDS['e:' + e['id']] = {'ch': n, 'kind': 'event', 'label': e['title'],
                                 'date': e.get('date', ''), 'year': e.get('year'), 'month': e.get('month')}
    for p in ch.get('people', []):
        CARDS['p:' + p['id']] = {'ch': n, 'kind': 'person', 'label': p['name'], 'date': '', 'year': None}
    for c in ch.get('culture', []):
        CARDS['c:' + c['id']] = {'ch': n, 'kind': 'culture', 'label': c['title'],
                                 'date': c.get('date', ''), 'year': c.get('year')}
    for i, t in enumerate(ch.get('terms', [])):
        CARDS['t:%d:%d' % (n, i)] = {'ch': n, 'kind': 'term', 'label': t['term'],
                                     'date': t.get('date', ''), 'year': t.get('year')}

KEYS = CORE['core300']['keys']
MIN = set(CORE['core150']['keys'])
by_ch = {}
for k in KEYS:
    by_ch.setdefault(ch_of(k), []).append(k)

planned = [c for chs, _, _ in PLAN for c in chs]
assert sorted(planned) == sorted(CHS), 'в плане должны быть все главы ровно один раз'

def sort_key(k):
    c = CARDS[k]
    # внутри главы: сначала события по годам — это сюжет, затем люди, понятия, культура
    return (c['ch'], KIND_ORDER[c['kind']], c['year'] if c['year'] is not None else 9999,
            c.get('month') or 0, c['label'])

blocks = []
for i, (chs, title, sub) in enumerate(PLAN, 1):
    keys = sorted([k for c in chs for k in by_ch.get(c, [])], key=sort_key)
    if not keys:
        continue
    per = sorted({CHS[c]['period'] for c in chs})
    blocks.append({
        'n': i,
        'title': title,
        'sub': sub,
        'chs': list(chs),
        'per': per[-1] if per[-1] else per[0],
        'span': SPANS[i - 1],
        'min': sum(1 for k in keys if k in MIN),
        'keys': keys,
    })

assert sum(len(b['keys']) for b in blocks) == len(KEYS)
assert len({k for b in blocks for k in b['keys']}) == len(KEYS)

if '--preview' in sys.argv:
    for b in blocks:
        print('\n%2d. %s — %d карточек (гл. %s, %s, из «минимума» %d)'
              % (b['n'], b['title'], len(b['keys']),
                 ', '.join(map(str, b['chs'])), b['span'], b['min']))
        for k in b['keys']:
            c = CARDS[k]
            print('      %-8s %-26s %s' % (c['kind'], (c['date'] or '')[:24], c['label']))
    sys.exit(0)

CORE['blocks'] = blocks
