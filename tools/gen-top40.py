# -*- coding: utf-8 -*-
"""Собирает «Топ-40» — карточки, которыми решается весь прошлый вариант экзамена.

В варианте 26.06.26 (HDATA.pastExam) 14 заданий: 5 вопросов с выбором ответа
и 9 хронологий по четыре пункта. Каждому пункту хронологии и каждому вопросу
сопоставлена карточка колоды. Вопрос о Левобережной Украине закрывает та же
карточка, что и одноимённый пункт хронологии, поэтому карточек ровно 40.

Для каждой карточки сохраняется, в каких заданиях варианта она нужна
(номер задания — как в тесте «Вариант 26.06.26»: сначала вопросы, затем
хронологии), — приложение показывает это задание на обороте карточки.
Результат дописывается в core.js как HCORE.top40.

Запуск:  python3 tools/gen-top40.py [--preview]
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def load_js(path):
    src = open(os.path.join(ROOT, path), encoding='utf-8').read()
    return json.loads(src[src.index('=') + 1:].strip().rstrip(';'))

D = load_js('data.js')
CORE = load_js('core.js')
PAST = D['pastExam']

# ---------- карточки колоды (ключи те же, что в index.html) ----------
CARDS = {}
for ch in D['chapters']:
    n = ch['chapter']
    for e in ch.get('events', []):
        CARDS['e:' + e['id']] = {'label': e['title'], 'date': e.get('date', ''),
                                 'year': e.get('year'), 'month': e.get('month')}
    for c in ch.get('culture', []):
        CARDS['c:' + c['id']] = {'label': c['title'], 'date': c.get('date', ''),
                                 'year': c.get('year'), 'month': None}
    for i, t in enumerate(ch.get('terms', [])):
        CARDS['t:%d:%d' % (n, i)] = {'label': t['term'], 'date': t.get('date', ''),
                                     'year': t.get('year'), 'month': None}

def card_year(c):
    # у понятий года нет – берём первый год из даты («1726–1730» → 1726)
    return c['year'] if c['year'] is not None else int(re.search(r'\d{3,4}', c['date']).group())

# ---------- план: задание варианта → карточка ----------
# вопросы с выбором ответа – по порядку в варианте
MCQ = [
    'e:c06_e13',  # Левобережная Украина – при Алексее Михайловиче: Переяславская рада (1654)
    'e:c03_e09',  # первый ярлык на великое княжение владимирское – Ярослав Всеволодович (1243)
    'c:c04_c01',  # собор Покрова на Рву – в честь взятия Казани (1552)
    'e:c03_e44',  # не при Иване IV – введение Юрьева дня: Судебник Ивана III (1497)
    'e:c16_e22',  # прорыв блокады Ленинграда – операция «Искра» (1943)
]

# пункты хронологий – по тексту пункта
SEQ = {
    'Невская битва': 'e:c03_e06',
    'Ледовое побоище': 'e:c03_e08',
    'Куликовская битва': 'e:c03_e23',
    'Разорение Москвы ханом Тохтамышем': 'e:c03_e24',
    'Учреждение патриаршества': 'e:c05_e04',
    'Столбовский мир': 'e:c05_e33',
    'Соляной бунт': 'e:c06_e07',
    'Отмена местничества': 'e:c06_e25',
    'Левобережная Украина': 'e:c06_e13',   # Переяславская рада
    'Сенат': 'e:c07_e25',
    'Эстляндия': 'e:c07_e37',              # Ништадтский мир
    'Верховный тайный совет': 't:8:2',
    'Кабинет министров': 't:8:5',
    'Восточная Белоруссия': 'e:c08_e23',   # первый раздел Речи Посполитой
    'Негласный комитет': 'e:c09_e01',
    'Указ о вольных хлебопашцах': 'e:c09_e04',
    'Бессарабия': 'e:c09_e11',             # Бухарестский мир
    'Свод законов Российской империи': 'e:c09_e39',
    'Положение о крестьянах, вышедших из крепостной зависимости': 'e:c10_e05',
    'Устав о наказаниях, налагаемых мировыми судьями': 'e:c10_e11',  # судебная реформа
    'Создание Предпарламента': 'e:c13_e12',
    'Созыв Учредительного собрания': 'e:c13_e18',
    'Гибель генерала Л. Г. Корнилова': 'e:c13_e25',
    'Мятеж Чехословацкого корпуса': 'e:c13_e26',
    'Штурм Перекопа': 'e:c13_e39',
    'Коллективизация': 't:15:3',
    'Начало гражданской войны в Испании': 'e:c15_e32',
    'Заключение Антикоминтерновского пакта': 'e:c15_e33',
    'Аншлюс Австрии': 'e:c15_e34',
    'Мюнхенские соглашения по Чехословакии': 'e:c15_e36',
    'Оборона Брестской крепости': 'e:c16_e03',
    'Битва за Москву': 'e:c16_e08',
    'Сталинградская битва': 'e:c16_e17',
    'Освобождение Белоруссии': 'e:c16_e35',
    'Освоение целины': 'e:c17_e15',
    'Подписание договора ОСВ-1': 'e:c18_e25',
}

# ---------- сборка ----------
M = len(PAST['mcq'])
deck = {}   # ключ → {'d': дата для списка, 'sort': (год, месяц), 'ex': [задания]}

def entry(key):
    assert key in CARDS, 'нет карточки %s' % key
    c = CARDS[key]
    return deck.setdefault(key, {'d': c['date'], 'sort': (card_year(c), c['month'] or 0), 'ex': []})

for i, key in enumerate(MCQ):
    entry(key)['ex'].append({'n': i + 1})

for s, task in enumerate(PAST['seq']):
    n = M + s + 1
    for j, it in enumerate(task['items']):
        assert it['t'] in SEQ, 'задание %d: не сопоставлен пункт «%s»' % (n, it['t'])
        key = SEQ[it['t']]
        c = CARDS[key]
        # карточка должна учить тот же год (и месяц, если он есть у обоих), что спрашивает задание
        assert card_year(c) == it['y'], 'задание %d, «%s»: год карточки %s ≠ %s' % (n, it['t'], card_year(c), it['y'])
        assert not (c['month'] and it.get('m')) or c['month'] == it['m'], \
            'задание %d, «%s»: месяц карточки %s ≠ %s' % (n, it['t'], c['month'], it['m'])
        e = entry(key)
        e['d'] = it['d']   # в списке – короткая дата, как в самом задании
        e['sort'] = (it['y'], it.get('m') or c['month'] or 0)
        e['ex'].append({'n': n, 'i': j})
    # порядок карточек по их датам должен совпадать с правильным порядком задания
    by_card = sorted(task['items'], key=lambda it: deck[SEQ[it['t']]]['sort'])
    by_exam = sorted(task['items'], key=lambda it: (it['y'], it.get('m') or 0))
    assert by_card == by_exam, 'задание %d: даты карточек дают другой порядок' % n

assert len(deck) == 40, 'в топе %d карточек, а не 40' % len(deck)

# тест по топ-40 собирает хронологии из любых четырёх карточек – порядок должен однозначно следовать из дат:
# карточки одного года различаются месяцем
by_year = {}
for k in deck:
    y, m = deck[k]['sort']
    by_year.setdefault(y, []).append(m)
for y, ms in by_year.items():
    assert len(ms) == 1 or (all(ms) and len(set(ms)) == len(ms)), \
        '%d год: у карточек нет месяцев или они совпадают – порядок неоднозначен' % y

def card_entry(k):
    y, m = deck[k]['sort']
    e = {'key': k, 'd': deck[k]['d'], 'y': y}
    if m:
        e['m'] = m
    e['ex'] = deck[k]['ex']
    return e

keys = sorted(deck, key=lambda k: (deck[k]['sort'], CARDS[k]['label']))
top = {
    'note': 'Топ-40: все факты, нужные для 14 заданий варианта 26.06.26 (HDATA.pastExam), '
            'по карточке на пункт, в порядке времени. d – дата для списка, y и m – год и месяц для порядка '
            'в хронологиях; ex – задания варианта: n – номер как в тесте (сначала %d вопросов, затем '
            'хронологии), i – пункт хронологии.' % M,
    'cards': [card_entry(k) for k in keys],
}

if '--preview' in sys.argv:
    for num, k in enumerate(keys, 1):
        print('%2d. %-12s %-58s зад. %s' % (num, deck[k]['d'], CARDS[k]['label'][:58],
                                           ', '.join(str(x['n']) for x in deck[k]['ex'])))
    sys.exit(0)

CORE['top40'] = top
out = 'window.HCORE=' + json.dumps(CORE, ensure_ascii=False, separators=(',', ':')) + ';\n'
open(os.path.join(ROOT, 'core.js'), 'w', encoding='utf-8').write(out)
print('core.js: %d байт, топ-40: %d карточек на %d заданий варианта'
      % (len(out.encode('utf-8')), len(keys), M + len(PAST['seq'])))
